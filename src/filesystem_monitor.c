int fs_init(void) { log_event("CO-5: Filesystem monitor initialized"); return 0; }
void fs_cleanup(void) { fs_unmap_config(); log_event("CO-5: FS cleanup"); }

void fs_show_open_fds(pid_t pid) {
    char d[MAX_PATH_LEN]; snprintf(d, sizeof(d), "/proc/%d/fd", pid);
    DIR *dir = opendir(d);
    if (!dir) { printf("  [ERROR] Cannot open %s\n", d); return; }
    printf("\n  === CO-5: OPEN FILE DESCRIPTORS (PID %d) ===\n", pid);
    printf("  FD    Type        Target\n");
    printf("  -----------------------------------------------\n");
    struct dirent *e;
    while ((e = readdir(dir)) != NULL) {
        if (e->d_name[0] == '.') continue;
        char lp[MAX_PATH_LEN * 2], tgt[MAX_PATH_LEN];
        snprintf(lp, sizeof(lp), "%s/%s", d, e->d_name);
        ssize_t len = readlink(lp, tgt, sizeof(tgt) - 1);
        if (len > 0) {
            tgt[len] = '\0';
            const char *type = "file";
            if (strstr(tgt, "pipe:")) type = "pipe";
            else if (strstr(tgt, "socket:")) type = "socket";
            else if (strstr(tgt, "/dev/")) type = "device";
            printf("  %-5s %-11s %s\n", e->d_name, type, tgt);
        }
    }
    printf("\n");
    closedir(dir);
}

void fs_show_fd_table(void) { fs_show_open_fds(getpid()); }

void fs_show_inode_info(const char *path) {
    struct stat st;
    if (stat(path, &st) == -1) { printf("  [ERROR] stat '%s': %s\n", path, strerror(errno)); return; }
    const char *type = "unknown";
    if (S_ISREG(st.st_mode)) type = "regular";
    else if (S_ISDIR(st.st_mode)) type = "directory";
    else if (S_ISLNK(st.st_mode)) type = "symlink";
    else if (S_ISFIFO(st.st_mode)) type = "FIFO";
    printf("\n  === CO-5: INODE INFO ===\n");
    printf("  Path: %s\n  Inode: %lu\n  Type: %s\n  Perms: %o\n",
           path, (unsigned long)st.st_ino, type, st.st_mode & 0777);
    printf("  Links: %lu | UID: %d | GID: %d\n",
           (unsigned long)st.st_nlink, st.st_uid, st.st_gid);
    printf("  Size: %ld bytes | Blocks: %ld\n\n", (long)st.st_size, (long)st.st_blocks);
}

void fs_demo_buffered_vs_unbuffered(void) {
    printf("\n  === CO-5: BUFFERED vs UNBUFFERED I/O ===\n\n");
    const int N = 10000;
    const char *line = "Hello supervisor IO test\n";
    size_t ll = strlen(line);
    struct timespec s, e;

    printf("  1) Unbuffered: %d x write() syscalls...\n", N);
    int fd = open("/tmp/sup_unbuf.txt", O_WRONLY | O_CREAT | O_TRUNC, 0644);
    clock_gettime(CLOCK_MONOTONIC, &s);
    for (int i = 0; i < N; i++) write(fd, line, ll);
    fsync(fd); close(fd);
    clock_gettime(CLOCK_MONOTONIC, &e);
    double ut = (e.tv_sec - s.tv_sec) + (e.tv_nsec - s.tv_nsec) / 1e9;
    printf("     Time: %.6f s\n\n", ut);

    printf("  2) Buffered: %d x fwrite() (libc batches)...\n", N);
    FILE *fp = fopen("/tmp/sup_buf.txt", "w");
    clock_gettime(CLOCK_MONOTONIC, &s);
    for (int i = 0; i < N; i++) fwrite(line, 1, ll, fp);
    fflush(fp); fclose(fp);
    clock_gettime(CLOCK_MONOTONIC, &e);
    double bt = (e.tv_sec - s.tv_sec) + (e.tv_nsec - s.tv_nsec) / 1e9;
    printf("     Time: %.6f s\n\n", bt);

    printf("  Buffered is %.1fx faster (fewer syscalls due to libc buffer)\n\n", ut / bt);
    unlink("/tmp/sup_unbuf.txt"); unlink("/tmp/sup_buf.txt");
    log_event("CO-5: Buffered vs unbuffered demo");
}

void fs_demo_mmap_io(void) {
    printf("\n  === CO-5: MEMORY-MAPPED FILE I/O ===\n\n");
    const char *f = "/tmp/sup_mmap.txt";
    const char *content = "This file is memory-mapped!\nNo read()/write() needed.\n";
    int fd = open(f, O_RDWR | O_CREAT | O_TRUNC, 0644);
    if (fd == -1) return;
    size_t cl = strlen(content);
    write(fd, content, cl);
    printf("  Created %s (%zu bytes)\n", f, cl);
    char *m = mmap(NULL, cl, PROT_READ | PROT_WRITE, MAP_SHARED, fd, 0);
    if (m == MAP_FAILED) { close(fd); return; }
    printf("  Mapped at %p. Content:\n  ---\n", (void*)m);
    for (size_t i = 0; i < cl; i++) putchar(m[i]);
    printf("  ---\n");
    m[0] = 'M'; m[1] = 'M'; m[2] = 'A'; m[3] = 'P';
    msync(m, cl, MS_SYNC);
    printf("  Modified via memory, synced to disk.\n\n");
    munmap(m, cl); close(fd); unlink(f);
    log_event("CO-5: mmap I/O demo done");
}

void fs_explore_proc_vfs(pid_t pid) {
    char path[MAX_PATH_LEN], buf[4096];
    printf("\n  === CO-5: /proc VFS EXPLORATION (PID %d) ===\n", pid);
    printf("  /proc is a virtual FS — content generated by kernel on-the-fly!\n\n");
    snprintf(path, sizeof(path), "/proc/%d/status", pid);
    printf("  -- %s --\n", path);
    FILE *fp = fopen(path, "r");
    if (fp) { int n = 0; while (fgets(buf, sizeof(buf), fp) && n++ < 8) printf("  %s", buf); fclose(fp); }
    snprintf(path, sizeof(path), "/proc/%d/exe", pid);
    char lnk[MAX_PATH_LEN];
    ssize_t l = readlink(path, lnk, sizeof(lnk) - 1);
    if (l > 0) { lnk[l] = '\0'; printf("\n  Executable: %s\n", lnk); }
    printf("\n");
}

int fs_mmap_config(const char *path) {
    int fd = open(path, O_RDONLY);
    if (fd == -1) return -1;
    struct stat st;
    if (fstat(fd, &st) == -1) { close(fd); return -1; }
    g_ctx.mmap_config_size = st.st_size;
    g_ctx.mmap_config = mmap(NULL, st.st_size, PROT_READ, MAP_PRIVATE, fd, 0);
    close(fd);
    if (g_ctx.mmap_config == MAP_FAILED) { g_ctx.mmap_config = NULL; return -1; }
    return 0;
}

void fs_unmap_config(void) {
    if (g_ctx.mmap_config) { munmap(g_ctx.mmap_config, g_ctx.mmap_config_size); g_ctx.mmap_config = NULL; }
}
